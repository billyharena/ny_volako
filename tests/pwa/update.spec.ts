import { expect, test } from '@playwright/test'
import { registerAccount } from '../helpers/local-auth'

test('mise à jour : formulaire, autre onglet, file persistante puis synchronisation', async ({ page, context }, testInfo) => {
  test.skip(process.env.LOCAL_AUTH_E2E !== '1', 'Supabase local requis.')
  await registerAccount(page)
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.route('**/rest/v1/rpc/apply_change', route => route.abort())
  await page.getByRole('link', { name: '+ Ajouter une dépense', exact: true }).click()
  await page.getByLabel('Motif', { exact: true }).fill('À conserver après mise à jour')
  await page.getByLabel('Catégorie', { exact: true }).selectOption({ label: 'Alimentation' })
  await page.getByLabel('Prix unitaire').fill('125')
  await page.request.post('/__test/release')
  await page.evaluate(async () => { await (await navigator.serviceWorker.getRegistration())!.update() })
  const update = page.getByRole('button', { name: 'Mettre à jour maintenant' })
  await expect(update).toBeVisible({ timeout: 30_000 })
  await update.click()
  await expect(page.getByRole('alert')).toContainText('Enregistrez ou fermez')
  await expect(page.getByLabel('Motif', { exact: true })).toHaveValue('À conserver après mise à jour')
  await page.getByRole('button', { name: 'Enregistrer la dépense' }).click()
  await expect(page.getByText('1 opération en attente', { exact: true })).toBeVisible()
  const peer = await context.newPage(); await peer.goto('/depenses')
  await update.click()
  await expect(page.getByRole('alert')).toContainText('Fermez les autres onglets')
  await page.screenshot({ path: testInfo.outputPath('mise-a-jour-protegee.png'), fullPage: true })
  await peer.close()
  await update.click()
  await expect(page.locator('meta[name="test-release"]')).toHaveAttribute('content', '2', { timeout: 30_000 })
  await expect(page.getByRole('link', { name: 'À conserver après mise à jour', exact: true })).toBeVisible()
  await expect(page.getByText('1 opération en attente', { exact: true })).toBeVisible()
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('link', { name: 'À conserver après mise à jour', exact: true })).toBeVisible()
  await context.unroute('**/rest/v1/rpc/apply_change')
  await context.setOffline(false)
  await page.getByRole('link', { name: 'Suivre la synchronisation' }).click()
  const sync = page.getByRole('button', { name: 'Synchroniser maintenant' })
  await expect(sync).toBeEnabled(); await sync.click()
  // Closing the peer can leave its durable lease alive for up to 60 seconds.
  await expect(page.getByText('0 opération en attente', { exact: true })).toBeVisible({ timeout: 90_000 })
})
