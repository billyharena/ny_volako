import { expect as baseExpect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { registerAccount } from '../helpers/local-auth'

const expect = baseExpect.configure({ timeout: 20_000 })
test.describe('carnet local', () => {
  test.skip(process.env.LOCAL_AUTH_E2E !== '1', 'Nécessite Supabase et Mailpit locaux.')
  test.setTimeout(180_000)
  test('budget, CRUD sans réseau, réouverture, export et séparation des comptes', async ({ page, context }, testInfo) => {
    const user = await registerAccount(page)
    await page.getByRole('link', { name: 'Budget', exact: true }).click()
    const month = await page.getByLabel('Mois du budget').inputValue()
    await page.getByLabel('Budget mensuel (MGA)').fill('100')
    await page.getByRole('button', { name: 'Enregistrer le budget' }).click()
    await expect(page.getByText('Budget enregistré sur cet appareil.')).toBeVisible()
    await page.getByRole('link', { name: 'Catégories', exact: true }).click()
    await page.getByLabel('Nom de la catégorie').first().fill('Voyage personnel')
    await page.getByRole('button', { name: 'Ajouter la catégorie' }).click()
    await expect(page.getByRole('heading', { name: 'Voyage personnel' })).toBeVisible()
    await page.getByRole('link', { name: '+ Ajouter une dépense', exact: true }).click()
    await expect(page.getByLabel('Quantité')).toHaveValue('1')
    await expect(page.getByLabel('Frais supplémentaires')).toHaveValue('0')
    await context.setOffline(true)
    await page.getByLabel('Date', { exact: true }).fill(`${month}-11`)
    await page.getByLabel('Motif', { exact: true }).fill('Achat sans réseau')
    await page.getByLabel('Catégorie', { exact: true }).selectOption({ label: 'Voyage personnel' })
    await page.getByLabel('Prix unitaire').fill('37,5')
    await page.getByLabel('Quantité').fill('2')
    await expect(page.locator('output')).toContainText('75,00 Ar')
    await page.getByRole('button', { name: 'Enregistrer la dépense' }).click()
    await expect(page.getByRole('link', { name: 'Achat sans réseau', exact: true })).toBeVisible()
    await expect(page.getByText('Seuil franchi : 70 %')).toBeVisible()
    await page.getByRole('button', { name: 'Masquer l’alerte' }).click()
    await page.getByRole('link', { name: 'Achat sans réseau', exact: true }).click()
    await page.getByLabel('Quantité').fill('3')
    await page.getByRole('button', { name: 'Enregistrer la dépense' }).click()
    await expect(page.getByText('Seuils franchis : 85 %, 100 %')).toBeVisible()
    await page.getByRole('button', { name: 'Masquer l’alerte' }).click()
    await page.getByRole('link', { name: 'Achat sans réseau', exact: true }).click()
    await page.getByRole('button', { name: 'Supprimer cette dépense' }).click()
    await page.getByRole('button', { name: 'Confirmer la suppression' }).click()
    await expect(page.getByRole('heading', { name: 'Aucune dépense à afficher' })).toBeVisible()
    await page.getByRole('link', { name: '+ Ajouter une dépense', exact: true }).click()
    await page.getByLabel('Date', { exact: true }).fill(`${month}-11`)
    await page.getByLabel('Motif', { exact: true }).fill('Dépense conservée')
    await page.getByLabel('Catégorie', { exact: true }).selectOption({ label: 'Voyage personnel' })
    await page.getByLabel('Prix unitaire').fill('75')
    await page.getByRole('button', { name: 'Enregistrer la dépense' }).click()
    await expect(page.getByText('Seuil franchi : 70 %')).toBeVisible()
    await page.getByRole('button', { name: 'Masquer l’alerte' }).click()
    await page.getByLabel('Rechercher un motif').fill('absent')
    await expect(page.getByRole('heading', { name: 'Aucune dépense à afficher' })).toBeVisible()
    await page.getByRole('button', { name: 'Effacer les filtres' }).click()
    await expect(page.getByText('Total filtré : 75,00 Ar')).toBeVisible()

    // Le shell n'est pas encore précaché : on rétablit le réseau pour le chargement HTML.
    await context.setOffline(false)
    await page.close()
    const reopened = await context.newPage()
    await reopened.goto('/depenses')
    await expect(reopened.getByRole('link', { name: 'Dépense conservée', exact: true })).toBeVisible()
    await expect(reopened.getByText(/Seuil franchi/)).toHaveCount(0)
    await reopened.getByRole('link', { name: 'Vue d’ensemble', exact: true }).click()
    await expect(reopened.getByRole('heading', { name: 'Évolution quotidienne' })).toBeVisible()
    await expect(reopened.getByText('75,00 %', { exact: true })).toBeVisible()
    expect(await reopened.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await reopened.screenshot({ path: testInfo.outputPath('dashboard.png'), fullPage: true })
    await reopened.getByRole('link', { name: 'Mon compte', exact: true }).click()
    await reopened.getByRole('button', { name: 'Se déconnecter de cet appareil' }).click()
    await expect(reopened.getByRole('alert')).toContainText('opérations restent en attente')
    const downloadPromise = reopened.waitForEvent('download')
    await reopened.getByRole('button', { name: 'Exporter les données locales' }).click()
    const download = await downloadPromise
    const exportPath = testInfo.outputPath('recovery.json')
    await download.saveAs(exportPath)
    const recovery = JSON.parse(await readFile(exportPath, 'utf8')) as { operations: { user_id: string }[]; data: { expenses: { deleted_at: string | null }[] } }
    expect(recovery.operations).toHaveLength(6)
    expect(recovery.data.expenses.filter(row => !row.deleted_at)).toHaveLength(1)
    await reopened.getByRole('checkbox', { name: /J’ai vérifié/ }).check()
    await reopened.getByRole('button', { name: 'Se déconnecter de cet appareil' }).click()
    await expect(reopened.getByRole('heading', { name: 'Heureux de vous retrouver.' })).toBeVisible()
    await registerAccount(reopened)
    await reopened.getByRole('link', { name: 'Dépenses', exact: true }).click()
    await expect(reopened.getByRole('heading', { name: 'Aucune dépense à afficher' })).toBeVisible()
    await expect(reopened.getByRole('link', { name: 'Dépense conservée', exact: true })).toHaveCount(0)
    await reopened.getByRole('link', { name: 'Mon compte', exact: true }).click()
    await reopened.getByRole('button', { name: 'Se déconnecter de cet appareil' }).click()
    await reopened.getByLabel('Adresse email').fill(user.email)
    await reopened.getByLabel('Mot de passe', { exact: true }).fill(user.password)
    await reopened.getByRole('button', { name: 'Se connecter' }).click()
    await reopened.getByRole('link', { name: 'Dépenses', exact: true }).click()
    await expect(reopened.getByRole('link', { name: 'Dépense conservée', exact: true })).toBeVisible()
    await expect(reopened.getByText('6 opérations en attente')).toBeVisible()
  })
})
