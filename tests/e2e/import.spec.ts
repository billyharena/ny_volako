import { expect as baseExpect, test } from '@playwright/test'
import { registerAccount } from '../helpers/local-auth'

const expect = baseExpect.configure({ timeout: 30_000 })
const csv = 'Motif,Date,Category,PU,Frais,Quantity,Montant sans frais,Montant avec frais\nBus CSV,2026-04-28,Mobility,600,0,4,2400,2400\nBus CSV,2026-04-28,Mobility,600,0,4,2400,2400\nRepas CSV,2026-04-28,Food,1000,50,2,2000,2050\nErreur CSV,2026-04-28,Food,1000,0,1,1000,9999'
test.describe('import CSV', () => {
  test.use({ actionTimeout: 30_000 })
  test.skip(process.env.LOCAL_AUTH_E2E !== '1', 'Supabase local requis.')
  test.setTimeout(180_000)
  test('aperçu, association, import hors ligne, réimport et synchronisation sur un autre appareil', async ({ page, context, browser }, testInfo) => {
    const user = await registerAccount(page)
    await page.getByRole('link', { name: 'Dépenses', exact: true }).click()
    await page.getByRole('link', { name: 'Importer des dépenses', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Importer des dépenses' })).toBeVisible()
    await context.setOffline(true)
    const upload = () => page.getByLabel('Fichier CSV', { exact: true }).setInputFiles({ name: 'depenses.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
    await upload()
    await page.getByRole('combobox', { name: 'Food', exact: true }).selectOption({ label: 'Alimentation' })
    await expect(page.getByLabel('Importer la ligne 2', { exact: true })).toBeChecked()
    await expect(page.getByLabel('Importer la ligne 3', { exact: true })).not.toBeChecked()
    await expect(page.getByLabel('Importer la ligne 5', { exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Confirmer l’import' })).toBeDisabled()
    await expect(page.getByText(/2 sélectionnée\(s\), soit 4/)).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('import-preview.png'), fullPage: true })
    await page.getByLabel(/Je confirme l’ajout/).check()
    await page.getByRole('button', { name: 'Confirmer l’import' }).click()
    await expect(page.getByText(/^2 dépense\(s\) importée\(s\)/)).toBeVisible()
    await upload()
    await page.getByRole('combobox', { name: 'Food', exact: true }).selectOption({ label: 'Alimentation' })
    await expect(page.getByText(/0 sélectionnée\(s\)/)).toBeVisible()
    await expect(page.getByRole('button', { name: 'Confirmer l’import' })).toBeDisabled()
    await context.setOffline(false)
    await page.getByRole('link', { name: 'Suivre la synchronisation' }).click()
    await page.getByRole('button', { name: 'Synchroniser maintenant' }).click()
    await expect(page.getByText('0 opération en attente', { exact: true })).toBeVisible({ timeout: 90_000 })
    const other = await browser.newContext({ baseURL: 'http://127.0.0.1:4173', viewport: { width: 390, height: 844 } })
    try {
      const second = await other.newPage()
      await second.goto('/connexion')
      await second.getByLabel('Adresse email').fill(user.email)
      await second.getByLabel('Mot de passe', { exact: true }).fill(user.password)
      await second.getByRole('button', { name: 'Se connecter', exact: true }).click()
      await expect(second.getByRole('heading', { name: 'Mon compte', exact: true })).toBeVisible()
      await second.getByRole('link', { name: 'Dépenses', exact: true }).click()
      await expect(second.getByRole('link', { name: 'Bus CSV', exact: true })).toHaveCount(1)
      await expect(second.getByRole('link', { name: 'Repas CSV', exact: true })).toHaveCount(1)
      await expect(second.getByRole('link', { name: 'Erreur CSV', exact: true })).toHaveCount(0)
      await expect(second.getByText(/Total filtré : 4.*450,00 Ar/)).toBeVisible()
      await second.getByRole('link', { name: 'Importer des dépenses', exact: true }).click()
      await second.getByLabel('Fichier CSV', { exact: true }).setInputFiles({ name: 'depenses.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
      await second.getByRole('combobox', { name: 'Food', exact: true }).selectOption({ label: 'Alimentation' })
      await expect(second.getByText(/0 sélectionnée\(s\)/)).toBeVisible()
      await second.screenshot({ path: testInfo.outputPath('import-mobile.png'), fullPage: true })
      expect(await second.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    } finally { await other.close() }
  })
})
